describe("sign in", () => {
  it("creates an account on the first Apple sign-in and finds it on the next", async () => {
    const sub = freshSub();
    const first = await signIn("apple", sub);
    expect(first.created).toBe(true);
    expect(first.account_id).toMatch(/^[A-Za-z0-9_-]{22}$/);
    expect(first.access_token).toMatch(/^a1\.[A-Za-z0-9_-]{22}\.[A-Za-z0-9_-]{43}$/);
    expect(first.refresh_token).toMatch(/^r1\.[A-Za-z0-9_-]{22}\.[A-Za-z0-9_-]{43}$/);
    expect(first.access_expires_in).toBe(3600);
    expect(first.refresh_expires_in).toBe(90 * 24 * 3600);
    expect(first.display_hint).toBeUndefined();

    const second = await signIn("apple", sub);
    expect(second).toMatchObject({ account_id: first.account_id, created: false });
    expect(second.access_token).not.toBe(first.access_token);

    const account = await get("/v1/account", second.access_token);
    expect(account.status).toBe(200);
    expect(await account.json()).toMatchObject({ account_id: first.account_id });
  });

  it("accepts the Apple Services ID as audience", async () => {
    expect((await signIn("apple", freshSub(), { aud: "com.jerryfane.herdr.signin" })).created).toBe(true);
  });

  it("signs in with Google from the iOS or the web client, and hands the email back only as a hint", async () => {
    const sub = freshSub();
    const ios = await signIn("google", sub);
    expect(ios.display_hint).toBe("luca@example.com");
    const web = await signIn("google", sub, { aud: GOOGLE_WEB_AUD, azp: GOOGLE_WEB_AUD, iss: "accounts.google.com" });
    expect(web.account_id).toBe(ios.account_id);
  });

  it("keeps Apple and Google users with the same sub apart", async () => {
    const sub = freshSub();
    const apple = await signIn("apple", sub);
    const google = await signIn("google", sub);
    expect(google.account_id).not.toBe(apple.account_id);
  });

  it("stores no provider user id and no email", async () => {
    const sub = freshSub();
    const tokens = await signIn("google", sub, { email: "only-a-hint@example.com" });
    const dump = JSON.stringify(
      await Promise.all(
        ["accounts", "identities", "sessions", "used_nonces"].map((table) => env.DB.prepare(`SELECT * FROM ${table}`).all()),
      ),
    );
    expect(dump).not.toContain(sub);
    expect(dump).not.toContain("only-a-hint");
    expect(dump).not.toContain(tokens.access_token.split(".")[2]);
    expect(dump).not.toContain(tokens.refresh_token.split(".")[2]);
  });

  it("finds one account when two first sign-ins race", async () => {
    const sub = freshSub();
    const [a, b] = await Promise.all([signIn("apple", sub), signIn("apple", sub)]);
    expect(a.account_id).toBe(b.account_id);
    const { results } = await env.DB.prepare("SELECT COUNT(*) AS n FROM sessions WHERE account_id = ?").bind(a.account_id).all<{ n: number }>();
    expect(results[0].n).toBe(2);
  });
});

describe("ID token checks", () => {
  async function attempt(
    provider: "apple" | "google",
    makeToken: (nonce: string) => Promise<string> | string,
    nonceFor: (nonce: string) => string = (nonce) => nonce,
  ): Promise<{ status: number; error: string; reason?: string }> {
    const nonce = await newNonce();
    const response = await post(`/v1/auth/${provider}`, { id_token: await makeToken(nonce), nonce: nonceFor(nonce), platform: "macos" });
    return rejection(response);
  }

  const now = () => nowSeconds();

  it.each([
    ["wrong issuer", { iss: "https://appleid.apple.com.evil" }, "wrong_issuer"],
    ["wrong audience", { aud: "com.example.other" }, "wrong_audience"],
    ["audience as an array", { aud: [APPLE_AUD] }, "wrong_audience"],
    ["expired", { exp: now() - 120 }, "expired"],
    ["issued in the future", { iat: now() + 300 }, "issued_in_future"],
    ["issued too long ago", { iat: now() - 11 * 60 }, "too_old"],
    ["without a nonce", { nonce: undefined }, "missing_nonce"],
    ["with an empty sub", { sub: "" }, "bad_subject"],
  ])("refuses an Apple token %s", async (_name, claims, reason) => {
    const result = await attempt("apple", (nonce) => signIdToken(keys.apple, appleClaims(freshSub(), nonce, claims)));
    expect(result).toEqual({ status: 401, error: "token_invalid", reason });
  });

  it("accepts Google's cross-client flow: aud is the web client, azp the iOS client", async () => {
    const tokens = await signIn("google", freshSub(), { aud: GOOGLE_WEB_AUD, azp: GOOGLE_IOS_AUD });
    expect(tokens.account_id).toMatch(/^[A-Za-z0-9_-]{22}$/);
  });

  it.each([
    ["another project's client", "other.apps.googleusercontent.com"],
    ["not a string", 7],
  ])("refuses a Google token whose azp is %s", async (_name, azp) => {
    const result = await attempt("google", (nonce) => signIdToken(keys.google, googleClaims(freshSub(), nonce, { azp })));
    expect(result).toEqual({ status: 401, error: "token_invalid", reason: "wrong_presenter" });
  });

  it("refuses a Google-signed token at the Apple endpoint", async () => {
    const result = await attempt("apple", (nonce) => signIdToken(keys.google, appleClaims(freshSub(), nonce)));
    expect(result).toEqual({ status: 401, error: "token_invalid", reason: "unknown_kid" });
  });

  it("refuses a token signed by an unpublished key under a published kid", async () => {
    const result = await attempt("apple", (nonce) => signIdToken(keys.stranger, appleClaims(freshSub(), nonce), { kid: keys.apple.kid }));
    expect(result).toEqual({ status: 401, error: "token_invalid", reason: "bad_signature" });
  });

  it("refuses a token whose payload was changed after signing", async () => {
    const result = await attempt("apple", async (nonce) => {
      const [head, , signature] = (await signIdToken(keys.apple, appleClaims(freshSub(), nonce))).split(".");
      return `${head}.${b64url(utf8(JSON.stringify(appleClaims("someone-else", nonce))))}.${signature}`;
    });
    expect(result).toEqual({ status: 401, error: "token_invalid", reason: "bad_signature" });
  });

  it.each([
    ["none", { alg: "none", kid: "apple-test-1" }],
    ["HS256", { alg: "HS256", kid: "apple-test-1" }],
    ["RS256 with crit", { alg: "RS256", kid: "apple-test-1", crit: ["exp"] }],
  ])("refuses alg %s", async (_name, header) => {
    const result = await attempt("apple", (nonce) => compactJws(header, appleClaims(freshSub(), nonce), utf8("sig")));
    expect(result).toEqual({ status: 401, error: "token_invalid", reason: "unsupported_alg" });
  });

  it.each([
    ["two parts", "a.b"],
    ["not base64url", "a.b.c!"],
    ["no kid", compactJws({ alg: "RS256" }, {}, utf8("sig"))],
  ])("refuses a malformed token (%s)", async (_name, token) => {
    const result = await attempt("apple", () => token);
    expect(result).toEqual({ status: 401, error: "token_invalid", reason: "malformed" });
  });

  it("refuses a token carrying another nonce than the one sent", async () => {
    const other = await newNonce();
    const result = await attempt("apple", () => signIdToken(keys.apple, appleClaims(freshSub(), other)));
    expect(result).toEqual({ status: 401, error: "token_invalid", reason: "nonce_mismatch" });
  });

  it("refuses a nonce this service did not issue", async () => {
    const forged = b64url(crypto.getRandomValues(new Uint8Array(40)));
    const result = await attempt("apple", () => signIdToken(keys.apple, appleClaims(freshSub(), forged)), () => forged);
    expect(result).toEqual({ status: 401, error: "nonce_invalid" });
  });

  it("refuses an expired nonce", async () => {
    const nonceKey = (await serviceKeys(env.ACCOUNT_HMAC_KEY)!).nonce;
    const { nonce: stale } = await issueNonce(nonceKey, Date.now() - 11 * 60 * 1000);
    const result = await attempt("apple", () => signIdToken(keys.apple, appleClaims(freshSub(), stale)), () => stale);
    expect(result).toEqual({ status: 401, error: "nonce_invalid" });
  });

  it("spends each nonce once", async () => {
    const nonce = await newNonce();
    const body = { id_token: await signIdToken(keys.apple, appleClaims(freshSub(), nonce)), nonce, platform: "ios" };
    expect((await post("/v1/auth/apple", body)).status).toBe(200);
    expect(await rejection(await post("/v1/auth/apple", body))).toEqual({ status: 401, error: "nonce_used" });
  });

  it.each([
    ["an unknown platform", { platform: "amiga" }],
    ["a missing id_token", { id_token: undefined }],
    ["a numeric nonce", { nonce: 7 }],
  ])("answers 400 to %s", async (_name, change) => {
    const nonce = await newNonce();
    const body = { id_token: await signIdToken(keys.apple, appleClaims(freshSub(), nonce)), nonce, platform: "ios", ...change };
    expect(await rejection(await post("/v1/auth/apple", body))).toEqual({ status: 400, error: "bad_request" });
  });

  it("answers 400 to a body that is not a JSON object, and 413 past 8 KB", async () => {
    expect((await post("/v1/auth/apple", "not json")).status).toBe(400);
    expect((await post("/v1/auth/apple", "[1,2]")).status).toBe(400);
    expect((await post("/v1/auth/apple", { id_token: "x".repeat(9000) })).status).toBe(413);
  });

  it("answers 500 not_configured while a provider has no client id", async () => {
    const saved = { ios: env.GOOGLE_IOS_CLIENT_ID, web: env.GOOGLE_WEB_CLIENT_ID };
    env.GOOGLE_IOS_CLIENT_ID = "";
    env.GOOGLE_WEB_CLIENT_ID = "";
    try {
      expect(await rejection(await post("/v1/auth/google", {}))).toEqual({ status: 500, error: "not_configured" });
    } finally {
      env.GOOGLE_IOS_CLIENT_ID = saved.ios;
      env.GOOGLE_WEB_CLIENT_ID = saved.web;
    }
  });

  it("answers 500 not_configured without a usable ACCOUNT_HMAC_KEY", async () => {
    const saved = env.ACCOUNT_HMAC_KEY;
    env.ACCOUNT_HMAC_KEY = "too-short";
    try {
      expect(await rejection(await post("/v1/auth/nonce", {}))).toEqual({ status: 500, error: "not_configured" });
    } finally {
      env.ACCOUNT_HMAC_KEY = saved;
    }
  });
});

describe("sessions", () => {
  async function refresh(refreshToken: string): Promise<Response> {
    return post("/v1/auth/refresh", { refresh_token: refreshToken });
  }

  it("rotates both tokens on refresh and retires the old access token", async () => {
    const first = await signIn("apple");
    const response = await refresh(first.refresh_token);
    expect(response.status).toBe(200);
    const second = await response.json<Tokens>();
    expect(second.account_id).toBe(first.account_id);
    expect(second.refresh_token).not.toBe(first.refresh_token);
    expect(second.refresh_token.split(".")[1]).toBe(first.refresh_token.split(".")[1]);
    expect((await get("/v1/account", first.access_token)).status).toBe(401);
    expect((await get("/v1/account", second.access_token)).status).toBe(200);
    expect((await refresh(second.refresh_token)).status).toBe(200);
  });

  it("treats a rotated-away refresh token as stolen and ends the whole session", async () => {
    const first = await signIn("google");
    const second = await (await refresh(first.refresh_token)).json<Tokens>();
    expect(await rejection(await refresh(first.refresh_token))).toEqual({ status: 401, error: "session_revoked" });
    expect(await rejection(await refresh(second.refresh_token))).toEqual({ status: 401, error: "invalid_token" });
    expect((await get("/v1/account", second.access_token)).status).toBe(401);
  });

  it("revokes the session when any earlier refresh token comes back, not just the last one", async () => {
    const r0 = await signIn("apple");
    const r1 = await (await refresh(r0.refresh_token)).json<Tokens>();
    const r2 = await (await refresh(r1.refresh_token)).json<Tokens>();
    expect(await rejection(await refresh(r0.refresh_token))).toEqual({ status: 401, error: "session_revoked" });
    expect(await rejection(await refresh(r2.refresh_token))).toEqual({ status: 401, error: "invalid_token" });
    expect((await get("/v1/account", r2.access_token)).status).toBe(401);
  });

  it("rotates and marks the account seen atomically: a failed refresh leaves the token usable", async () => {
    const tokens = await signIn("apple");
    await env.DB.prepare("UPDATE accounts SET last_seen_day = 5 WHERE id = ?").bind(tokens.account_id).run();
    // Make the account touch fail, as a D1 error mid-refresh would.
    const trigger = `fail_touch_${randomB64url(6).replace(/-/g, "_")}`;
    await env.DB.prepare(
      `CREATE TRIGGER ${trigger} BEFORE UPDATE OF last_seen_day ON accounts WHEN OLD.id = '${tokens.account_id}'
       BEGIN SELECT RAISE(ABORT, 'touch failed'); END`,
    ).run();
    try {
      expect(await rejection(await refresh(tokens.refresh_token))).toEqual({ status: 500, error: "internal_error" });
    } finally {
      await env.DB.prepare(`DROP TRIGGER ${trigger}`).run();
    }
    expect((await get("/v1/account", tokens.access_token)).status).toBe(200);
    const retried = await refresh(tokens.refresh_token);
    expect(retried.status).toBe(200);
    const row = await env.DB.prepare("SELECT last_seen_day FROM accounts WHERE id = ?").bind(tokens.account_id).first<{ last_seen_day: number }>();
    expect(row?.last_seen_day).toBe(dayOf(Date.now()));
  });

  it("lets the first of two racing refreshes win and revokes the session for the second", async () => {
    const tokens = await signIn("apple");
    const answers = await Promise.all([refresh(tokens.refresh_token), refresh(tokens.refresh_token)]);
    const statuses = answers.map((answer) => answer.status).sort();
    expect(statuses).toEqual([200, 401]);
    const winner = await answers.find((answer) => answer.status === 200)!.json<Tokens>();
    const loser = await answers.find((answer) => answer.status === 401)!.json<{ error: string }>();
    expect(loser.error).toBe("session_revoked");
    expect((await get("/v1/account", winner.access_token)).status).toBe(401);
    expect(await rejection(await refresh(winner.refresh_token))).toEqual({ status: 401, error: "invalid_token" });
  });

  it("refuses unknown, malformed and expired refresh tokens without touching the session", async () => {
    const tokens = await signIn("apple");
    const [, sessionId] = tokens.refresh_token.split(".");
    expect(await rejection(await refresh(`r1.${sessionId}.${"A".repeat(43)}`))).toEqual({ status: 401, error: "invalid_token" });
    expect(await rejection(await refresh("r1.nope"))).toEqual({ status: 401, error: "invalid_token" });
    expect(await rejection(await refresh(tokens.access_token))).toEqual({ status: 401, error: "invalid_token" });
    expect((await get("/v1/account", tokens.access_token)).status).toBe(200);

    await env.DB.prepare("UPDATE sessions SET refresh_exp_ms = ? WHERE id = ?").bind(Date.now() - 1, sessionId).run();
    expect(await rejection(await refresh(tokens.refresh_token))).toEqual({ status: 401, error: "invalid_token" });
  });

  it("answers token_expired for an access token past its hour", async () => {
    const tokens = await signIn("apple");
    const [, sessionId] = tokens.access_token.split(".");
    await env.DB.prepare("UPDATE sessions SET access_exp_ms = ? WHERE id = ?").bind(Date.now() - 1, sessionId).run();
    const response = await get("/v1/account", tokens.access_token);
    expect(response.headers.get("WWW-Authenticate")).toBe("Bearer");
    expect(await rejection(response)).toEqual({ status: 401, error: "token_expired" });
  });

  it("refuses a missing, malformed or forged access token", async () => {
    const tokens = await signIn("apple");
    const [, sessionId] = tokens.access_token.split(".");
    expect((await get("/v1/account")).status).toBe(401);
    expect((await get("/v1/account", "a1.x.y")).status).toBe(401);
    expect(await rejection(await get("/v1/account", `a1.${sessionId}.${"B".repeat(43)}`))).toEqual({ status: 401, error: "invalid_token" });
  });

  it("signs out: both tokens stop working", async () => {
    const tokens = await signIn("google");
    const out = await post("/v1/auth/signout", {}, freshIp(), { Authorization: `Bearer ${tokens.access_token}` });
    expect(out.status).toBe(204);
    expect((await get("/v1/account", tokens.access_token)).status).toBe(401);
    expect((await refresh(tokens.refresh_token)).status).toBe(401);
  });

  it("marks the account seen on refresh, at most once a day", async () => {
    const tokens = await signIn("apple");
    await env.DB.prepare("UPDATE accounts SET last_seen_day = 5 WHERE id = ?").bind(tokens.account_id).run();
    await refresh(tokens.refresh_token);
    const row = await env.DB.prepare("SELECT last_seen_day FROM accounts WHERE id = ?").bind(tokens.account_id).first<{ last_seen_day: number }>();
    expect(row?.last_seen_day).toBe(dayOf(Date.now()));
  });
});

describe("rate limits", () => {
  it("allows 20 sign-in calls per IP a minute, and another IP its own 20", async () => {
    const ip = freshIp();
    for (let i = 0; i < 20; i++) expect((await post("/v1/auth/nonce", {}, ip)).status).toBe(200);
    expect(await rejection(await post("/v1/auth/nonce", {}, ip))).toEqual({ status: 429, error: "rate_limited" });
    expect((await post("/v1/auth/refresh", { refresh_token: "r1.x" }, ip)).status).toBe(429);
    expect((await post("/v1/auth/nonce", {}, freshIp())).status).toBe(200);
  });

  it("allows 120 account calls per account a minute", async () => {
    const tokens = await signIn("apple");
    for (let i = 0; i < 120; i++) expect((await get("/v1/account", tokens.access_token)).status).toBe(200);
    expect(await rejection(await get("/v1/account", tokens.access_token))).toEqual({ status: 429, error: "rate_limited" });
    const other = await signIn("apple");
    expect((await get("/v1/account", other.access_token)).status).toBe(200);
  });
});

