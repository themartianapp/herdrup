// Everything here runs against the real Worker and a local D1 database in workerd. Apple's
// and Google's keys are generated by the tests (test/providers.ts). Each test uses its own
// provider user ids and client IPs, so rows never collide. The rate-limit bindings are
// per-key counters with wrangler.toml's limits that start at zero in each test (test/setup.ts).

const ORIGIN = "https://accounts.herdrup.app";
const APPLE_AUD = "com.jerryfane.herdr";
const GOOGLE_IOS_AUD = "test-ios.apps.googleusercontent.com";
const GOOGLE_WEB_AUD = "test-web.apps.googleusercontent.com";

let keys: Providers;
let ipCounter = 0;
let subCounter = 0;
const freshIp = () => `2001:db8::${(++ipCounter).toString(16)}`;
const freshSub = () => `001234.${crypto.randomUUID().replace(/-/g, "")}.${++subCounter}`;

beforeAll(async () => {
  keys = await fakeProviders();
});

function post(path: string, body: unknown, ip = freshIp(), headers: Record<string, string> = {}): Promise<Response> {
  return SELF.fetch(`${ORIGIN}${path}`, {
    method: "POST",
    headers: { "content-type": "application/json", "CF-Connecting-IP": ip, ...headers },
    body: typeof body === "string" ? body : JSON.stringify(body),
  });
}

function get(path: string, accessToken?: string): Promise<Response> {
  return SELF.fetch(`${ORIGIN}${path}`, {
    headers: accessToken === undefined ? {} : { Authorization: `Bearer ${accessToken}` },
  });
}

async function newNonce(ip = freshIp()): Promise<string> {
  const response = await post("/v1/auth/nonce", {}, ip);
  expect(response.status).toBe(200);
  const body = await response.json<{ nonce: string; expires_unix: number }>();
  return body.nonce;
}

const nowSeconds = () => Math.floor(Date.now() / 1000);

function appleClaims(sub: string, nonce: string, extra: Record<string, unknown> = {}): Record<string, unknown> {
  return { iss: "https://appleid.apple.com", aud: APPLE_AUD, sub, nonce, iat: nowSeconds(), exp: nowSeconds() + 600, ...extra };
}

function googleClaims(sub: string, nonce: string, extra: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    iss: "https://accounts.google.com",
    aud: GOOGLE_IOS_AUD,
    azp: GOOGLE_IOS_AUD,
    sub,
    nonce,
    email: "luca@example.com",
    email_verified: true,
    iat: nowSeconds(),
    exp: nowSeconds() + 3600,
    ...extra,
  };
}

interface Tokens {
  account_id: string;
  created: boolean;
  access_token: string;
  access_expires_in: number;
  refresh_token: string;
  refresh_expires_in: number;
  display_hint?: string;
}

async function signIn(
  provider: "apple" | "google",
  sub = freshSub(),
  extra: Record<string, unknown> = {},
  key?: SigningKey,
): Promise<Tokens> {
  const nonce = await newNonce();
  const claims = provider === "apple" ? appleClaims(sub, nonce, extra) : googleClaims(sub, nonce, extra);
  const idToken = await signIdToken(key ?? keys[provider], claims);
  const response = await post(`/v1/auth/${provider}`, { id_token: idToken, nonce, platform: "ios" });
  expect(response.status).toBe(200);
  return response.json<Tokens>();
}

async function rejection(response: Response): Promise<{ status: number; error: string; reason?: string }> {
  const body = await response.json<{ error: string; reason?: string }>();
  return { status: response.status, ...body };
}

